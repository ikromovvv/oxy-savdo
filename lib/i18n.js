// Tarjima: avval o'z tili; topilmasa — yangi tillar uchun ingliz, keyin o'zbek, oxirida kalitning o'zi
export function t(lang, key) {
  const own = dict[lang]?.[key];
  if (own != null) return own;
  if (lang !== 'uz' && lang !== 'ru') {
    const en = dict.en[key];
    if (en != null) return en;
  }
  return dict.uz[key] ?? key;
}

// Ikki tilli ({uz, ru, en...}) matn/obyektdan joriy til qiymatini tanlaydi; yo'q bo'lsa ingliz -> rus -> o'zbek
export function pick(obj, lang) {
  if (!obj) return '';
  return obj[lang] ?? obj.en ?? obj.ru ?? obj.uz ?? '';
}
